BEGIN;
-- Isolate synthetic evaluations from default teacher templates; rollback restores them.
UPDATE public.jds_bulletin_subjects SET active=false;
CREATE TEMP TABLE bulletin_test_ids(k text,v uuid);
DO $test$
DECLARE teacher_id uuid:=gen_random_uuid(); student_id uuid:=gen_random_uuid(); peer uuid:=gen_random_uuid(); director uuid:=gen_random_uuid(); jacky uuid:=gen_random_uuid(); person uuid:=gen_random_uuid(); grp uuid; member uuid; subj uuid; subj2 uuid; report uuid; payload jsonb; denied boolean; admin_id uuid; req uuid;
BEGIN
 SELECT id INTO admin_id FROM public.profiles WHERE 'admin'=ANY(roles) LIMIT 1;
 SELECT id INTO grp FROM public.jds_training_groups WHERE campus='INDUSTRY' AND name='P2' AND season='2026-2027';
 INSERT INTO auth.users(id,email,raw_user_meta_data) VALUES(teacher_id,'bulletin-teacher@example.invalid','{}'),(student_id,'bulletin-student@example.invalid','{}'),(peer,'bulletin-peer@example.invalid','{}'),(director,'bulletin-director@example.invalid','{}'),(jacky,'bulletin-jacky@example.invalid','{}');
 UPDATE auth.users SET email_confirmed_at=now() WHERE id IN(teacher_id,student_id,peer,director,jacky);
 UPDATE public.jds_school_responsibilities SET profile_id=director,enabled=true WHERE email='loic@juste-debout.com';
 UPDATE public.jds_school_responsibilities SET profile_id=jacky,enabled=true WHERE email='jacky@juste-debout.com';
 INSERT INTO public.jds_access_requests(profile_id,kind,campus,status) VALUES(teacher_id,'teacher','INDUSTRY','approved');
 INSERT INTO public.jds_private_directory(id,external_key,campus,person_type,first_name,last_name) VALUES(person,person::text,'INDUSTRY','student','Test','Bulletin');
 INSERT INTO public.jds_training_members(group_id,person_id) VALUES(grp,person) RETURNING id INTO member;
 PERFORM set_config('request.jwt.claim.sub',student_id::text,true);
 req:=public.jds_submit_student_request('formation','INDUSTRY',grp,'');
 PERFORM set_config('request.jwt.claim.sub',admin_id::text,true);
 PERFORM public.jds_review_student_request(req,'approved',person,'Test bulletin');
 PERFORM set_config('request.jwt.claim.sub',director::text,true);
 subj:=public.jds_save_bulletin_subject(grp,3,'Test bulletin Hip-Hop',teacher_id,'Prof test',2,1);
 subj2:=public.jds_save_bulletin_subject(grp,3,'Test bulletin House',teacher_id,'Prof test',1,3);
 PERFORM public.jds_save_bulletin_draft(member,3,'Progression régulière',0,1);
 denied:=false;BEGIN PERFORM public.jds_preview_bulletin(member,3);EXCEPTION WHEN raise_exception THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Missing grades accepted';END IF;
 PERFORM set_config('request.jwt.claim.sub',teacher_id::text,true);
 PERFORM public.jds_save_bulletin_grade(subj,member,ARRAY[4,5]::numeric[],ARRAY[12,16]::numeric[],false,false,'Bon travail',true);
 PERFORM public.jds_save_bulletin_grade(subj2,member,ARRAY[0]::numeric[],ARRAY[18]::numeric[],false,false,'À poursuivre',true);
 denied:=false;BEGIN PERFORM public.jds_save_bulletin_grade(subj,member,ARRAY[3]::numeric[],ARRAY[12]::numeric[],false,false,'Edit',false,1);EXCEPTION WHEN raise_exception THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Teacher edited submitted scores';END IF;
 denied:=false;BEGIN PERFORM public.jds_publish_bulletin(member,3);EXCEPTION WHEN raise_exception THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Teacher published';END IF;
 PERFORM set_config('request.jwt.claim.sub',jacky::text,true);
 IF NOT public.jds_can_manage_school('INDUSTRY') OR school_private.bulletin_can_publish('INDUSTRY') THEN RAISE EXCEPTION 'Jacky scope';END IF;
 PERFORM set_config('request.jwt.claim.sub',director::text,true);
 IF NOT school_private.bulletin_can_publish('CORE') OR NOT school_private.bulletin_can_publish('INDUSTRY') THEN RAISE EXCEPTION 'Director must publish for both campuses';END IF;
 payload:=public.jds_preview_bulletin(member,3);
 IF (payload->>'cc_average20')::numeric<>12 OR (payload->>'evaluation_average20')::numeric<>17 OR (payload->'rows'->0->>'cc20') IS NULL THEN RAISE EXCEPTION 'Weighted calculations failed: %',payload;END IF;
 report:=public.jds_publish_bulletin(member,3);
 IF (SELECT snapshot->>'address' FROM public.jds_bulletin_reports WHERE id=report)<>'27 boulevard de la Somme, 75017 Paris' THEN RAISE EXCEPTION 'Industry address';END IF;
 denied:=false;BEGIN UPDATE public.jds_bulletin_reports SET snapshot='{}' WHERE id=report;EXCEPTION WHEN raise_exception THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Mutable report';END IF;
 denied:=false;BEGIN PERFORM public.jds_publish_bulletin(member,3,1,'');EXCEPTION WHEN raise_exception THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Correction missing reason';END IF;
 PERFORM public.jds_save_bulletin_grade(subj2,member,'{}',ARRAY[18]::numeric[],true,false,'Dispense CC',true,1);
 payload:=public.jds_preview_bulletin(member,3);
 IF (payload->>'cc_average20')::numeric<>18 THEN RAISE EXCEPTION 'Exemption treated as zero';END IF;
 PERFORM public.jds_publish_bulletin(member,3,1,'Dispense CC corrigée');
 IF (SELECT (snapshot->>'cc_average20')::numeric FROM public.jds_bulletin_reports WHERE id=report)<>12 THEN RAISE EXCEPTION 'Original snapshot changed';END IF;
 denied:=false;BEGIN PERFORM public.jds_save_bulletin_grade(subj2,member,'{}','{}',true,true,'Conflict',false,1);EXCEPTION WHEN raise_exception THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Revision conflict ignored';END IF;
 -- Removing a line excludes it from calculation without losing grades or reports.
 PERFORM public.jds_set_bulletin_subject_active(subj2,false);
 payload:=public.jds_preview_bulletin(member,3);
 IF jsonb_array_length(payload->'rows')<>1 OR (payload->>'evaluation_average20')::numeric<>14 THEN RAISE EXCEPTION 'Removed subject still counted';END IF;
 IF NOT EXISTS(SELECT 1 FROM public.jds_bulletin_grades WHERE subject_id=subj2) THEN RAISE EXCEPTION 'Removed grade destroyed';END IF;
 IF (SELECT (snapshot->>'cc_average20')::numeric FROM public.jds_bulletin_reports WHERE id=report)<>12 THEN RAISE EXCEPTION 'Removal changed published report';END IF;
 PERFORM set_config('request.jwt.claim.sub',teacher_id::text,true);
 IF school_private.bulletin_can_grade(subj2) THEN RAISE EXCEPTION 'Teacher can grade removed subject';END IF;
 denied:=false;BEGIN PERFORM public.jds_set_bulletin_subject_active(subj2,true);EXCEPTION WHEN raise_exception THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Teacher restored subject';END IF;
 PERFORM set_config('request.jwt.claim.sub',director::text,true);
 PERFORM public.jds_set_bulletin_subject_active(subj2,true);
 payload:=public.jds_preview_bulletin(member,3);
 IF jsonb_array_length(payload->'rows')<>2 THEN RAISE EXCEPTION 'Restoration failed';END IF;
 -- Same discipline may have two independent teacher lines.
 PERFORM public.jds_save_bulletin_subject(grp,3,'Test bulletin Hip-Hop',NULL,'Another teacher',NULL,NULL);
 PERFORM public.jds_set_bulletin_subject_active((SELECT id FROM public.jds_bulletin_subjects WHERE group_id=grp AND term=3 AND subject='Test bulletin Hip-Hop' AND teacher_name='Another teacher'),false);
 PERFORM public.jds_save_bulletin_subject(grp,3,'Test bulletin House',teacher_id,'Prof test',NULL,3,0,subj2);
 denied:=false;BEGIN PERFORM public.jds_preview_bulletin(member,3);EXCEPTION WHEN raise_exception THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Missing coefficient accepted';END IF;
 INSERT INTO bulletin_test_ids VALUES('teacher',teacher_id),('student',student_id),('peer',peer),('report',report),('member',member),('subject',subj);
 IF has_function_privilege('anon','public.jds_bulletin_context()','EXECUTE') OR has_table_privilege('authenticated','public.jds_bulletin_grades','UPDATE') THEN RAISE EXCEPTION 'Unsafe grants';END IF;
END $test$;
GRANT SELECT ON bulletin_test_ids TO authenticated;
SELECT set_config('request.jwt.claim.sub',(SELECT v::text FROM bulletin_test_ids WHERE k='student'),true);
SET LOCAL ROLE authenticated;
DO $$BEGIN
 IF EXISTS(SELECT 1 FROM public.jds_bulletin_grades) OR EXISTS(SELECT 1 FROM public.jds_bulletin_drafts) THEN RAISE EXCEPTION 'Student saw draft grades';END IF;
 IF (SELECT count(*) FROM public.jds_bulletin_reports)<>2 THEN RAISE EXCEPTION 'Student missing own reports';END IF;
 IF (SELECT count(*) FROM public.jds_bulletin_notices)<>2 THEN RAISE EXCEPTION 'Student notices';END IF;
 PERFORM public.jds_read_bulletin_notice((SELECT v FROM bulletin_test_ids WHERE k='report'));
END $$;
RESET ROLE;
SELECT set_config('request.jwt.claim.sub',(SELECT v::text FROM bulletin_test_ids WHERE k='peer'),true);
SET LOCAL ROLE authenticated;
DO $$BEGIN IF EXISTS(SELECT 1 FROM public.jds_bulletin_reports) OR EXISTS(SELECT 1 FROM public.jds_bulletin_notices) THEN RAISE EXCEPTION 'Peer saw private report';END IF;END $$;
RESET ROLE;
SELECT set_config('request.jwt.claim.sub',(SELECT v::text FROM bulletin_test_ids WHERE k='teacher'),true);
SET LOCAL ROLE authenticated;
DO $$BEGIN IF (SELECT count(*) FROM public.jds_bulletin_subjects)<>2 OR EXISTS(SELECT 1 FROM public.jds_bulletin_reports) OR EXISTS(SELECT 1 FROM public.jds_bulletin_drafts) THEN RAISE EXCEPTION 'Teacher RLS scope';END IF;END $$;
RESET ROLE;
ROLLBACK;
